@dataclasses.dataclass
class CallProfile:
    total_calls: int
    kdl_calls: int
    by_func: dict[str, int]
    abc_calls: int


def profile_calls(fn: t.Callable[[], t.Any]) -> tuple[t.Any, CallProfile]:
    pr = cProfile.Profile()
    pr.enable()
    result = fn()
    pr.disable()
    ps_any = t.cast("t.Any", pstats.Stats(pr))
    kdl_calls = 0
    abc_calls = 0
    by_func: dict[str, int] = {}
    for (fname, _line, func), (_cc, nc, _tt, _ct, _) in ps_any.stats.items():
        norm = os.path.normpath(fname) if not fname.startswith("<") else fname
        if norm == KDL_ROOT or norm.startswith(KDL_ROOT + os.sep):
            kdl_calls += nc
            by_func[func] = by_func.get(func, 0) + nc
        elif "_abc_" in func:
            abc_calls += nc
    return result, CallProfile(
        total_calls=int(ps_any.total_calls),
        kdl_calls=kdl_calls,
        by_func=by_func,
        abc_calls=abc_calls,
    )


def measure_peak_kb(fn: t.Callable[[], t.Any]) -> float:
    gc.collect()
    tracemalloc.start()
    try:
        fn()
        _cur, peak = tracemalloc.get_traced_memory()
    finally:
        tracemalloc.stop()
    return peak / 1024.0


def clear_ident_cache() -> None:
    # Accessing the internal caches ensures deterministic cold-start print call counts.
    kdl_types._IDENT_CACHE.clear()  # pylint: disable=protected-access
    kdl_types._AUTO_STR_CACHE.clear()  # pylint: disable=protected-access
    kdl_types._QUOTED_STR_CACHE.clear()  # pylint: disable=protected-access


def check_max_int(name: str, value: int, limit: int, detail: str = "") -> CheckResult:
    return CheckResult(
        name=name,
        passed=value <= limit,
        measured=f"{value:,}",
        limit=f"<= {limit:,}",
        detail=detail,
    )


def check_max_float(name: str, value: float, limit: float, unit: str = "", detail: str = "") -> CheckResult:
    return CheckResult(
        name=name,
        passed=value <= limit,
        measured=f"{value:.2f}{unit}",
        limit=f"<= {limit:.2f}{unit}",
        detail=detail,
    )


# ---------------------------------------------------------------------------
# Suite 1: Deterministic call-count & hot-path invariant checks
# ---------------------------------------------------------------------------


def run_call_count_checks(doc_text: str) -> list[CheckResult]:
    results: list[CheckResult] = []
    native_cfg = kdl.ParseConfig()
    raw_cfg = kdl.ParseConfig(nativeUntaggedValues=False, nativeTaggedValues=False)

    # Warm up one-time stdlib lazy initializers (e.g. urllib/ipaddress) so total_calls is deterministic.
    kdl.parse(doc_text, native_cfg)

    doc_nat, prof_pn = profile_calls(lambda: kdl.parse(doc_text, native_cfg))
    doc_raw, prof_pr = profile_calls(lambda: kdl.parse(doc_text, raw_cfg))

    clear_ident_cache()
    _, prof_tn = profile_calls(doc_nat.print)
    clear_ident_cache()
    _, prof_tr = profile_calls(doc_raw.print)

    results.extend(
        [
            check_max_int("calls.parse_native.kdl", prof_pn.kdl_calls, MAX_PARSE_NATIVE_KDL_CALLS),
            check_max_int("calls.parse_native.total", prof_pn.total_calls, MAX_PARSE_NATIVE_TOTAL_CALLS),
            check_max_int(
                "calls.parse_native.finalize",
                prof_pn.by_func.get("_finalizeValue", 0),
                MAX_PARSE_NATIVE_FINALIZE_CALLS,
                "fastUntagged should skip _finalizeValue for untagged values",
            ),
            check_max_int(
                "calls.parse_native.skipNodespace",
                prof_pn.by_func.get("_skipNodespace", 0),
                MAX_PARSE_NATIVE_SKIP_NODESPACE_CALLS,
                "single-space separator fast path should avoid _skipNodespace",
            ),
            check_max_int(
                "calls.parse_native.loc",
                prof_pn.by_func.get("loc", 0),
                MAX_PARSE_NATIVE_LOC_CALLS,
                "Stream.loc should only be computed on ParseError",
            ),
            check_max_int(
                "calls.parse_native.abc",
                prof_pn.abc_calls,
                MAX_ABC_INSTANCECHECK_CALLS,
                "Value hierarchy should not incur ABCMeta isinstance overhead",
            ),
            check_max_int("calls.parse_raw.kdl", prof_pr.kdl_calls, MAX_PARSE_RAW_KDL_CALLS),
            check_max_int("calls.parse_raw.total", prof_pr.total_calls, MAX_PARSE_RAW_TOTAL_CALLS),
            check_max_int("calls.print_native.kdl", prof_tn.kdl_calls, MAX_PRINT_NATIVE_KDL_CALLS),
            check_max_int("calls.print_native.total", prof_tn.total_calls, MAX_PRINT_NATIVE_TOTAL_CALLS),
            check_max_int(
                "calls.print_native.printIdent",
                prof_tn.by_func.get("_printIdent", 0)
                + prof_tn.by_func.get("_printAutoString", 0)
                + prof_tn.by_func.get("_printQuotedString", 0),
                MAX_PRINT_NATIVE_IDENT_CALLS,
                "string cache inline lookups should avoid repeated string formatting calls",
            ),
            check_max_int("calls.print_raw.kdl", prof_tr.kdl_calls, MAX_PRINT_RAW_KDL_CALLS),
            check_max_int("calls.print_raw.total", prof_tr.total_calls, MAX_PRINT_RAW_TOTAL_CALLS),
            check_max_int(
                "calls.print_raw.printIdent",
                prof_tr.by_func.get("_printIdent", 0)
                + prof_tr.by_func.get("_printAutoString", 0)
                + prof_tr.by_func.get("_printQuotedString", 0),
                MAX_PRINT_RAW_IDENT_CALLS,
                "string cache inline lookups should avoid repeated string formatting calls",
            ),
            check_max_int(
                "calls.print_raw.abc",
                prof_tr.abc_calls,
                MAX_ABC_INSTANCECHECK_CALLS,
                "Value hierarchy should not incur ABCMeta isinstance overhead",
            ),
        ],
    )
    return results


# ---------------------------------------------------------------------------
# Suite 2: Peak memory budgets
# ---------------------------------------------------------------------------


def run_memory_checks(doc_text: str) -> list[CheckResult]:
    native_cfg = kdl.ParseConfig()
    doc_nat = kdl.parse(doc_text, native_cfg)
    # Warm the bounded ident cache once so print peak memory reflects steady-state printing.
    doc_nat.print()

    parse_peak_kb = measure_peak_kb(lambda: kdl.parse(doc_text, native_cfg))
    print_peak_kb = measure_peak_kb(doc_nat.print)

    return [
        check_max_float("memory.parse_native.peak", parse_peak_kb, MAX_PARSE_NATIVE_PEAK_KB, " KB"),
        check_max_float("memory.print_native.peak", print_peak_kb, MAX_PRINT_NATIVE_PEAK_KB, " KB"),
    ]


# ---------------------------------------------------------------------------
# Suite 3: Asymptotic O(N) / O(1) scaling checks (4x vs 1x input size)
# ---------------------------------------------------------------------------


def _measure_scaling(
    small_fn: t.Callable[[], t.Any],
    big_fn: t.Callable[[], t.Any],
    rounds: int = 5,
) -> tuple[float, float]:
    # Warmup
    small_fn()
    big_fn()

    # Deterministic call-count ratio
    _, prof_s = profile_calls(small_fn)
    _, prof_b = profile_calls(big_fn)
    call_ratio = prof_b.kdl_calls / max(1, prof_s.kdl_calls)

    # Interleaved minimum-time ratio (min eliminates OS scheduler spikes)
    small_times: list[float] = []
    big_times: list[float] = []
    for _ in range(rounds):
        t0 = time.perf_counter()
        small_fn()
        small_times.append(time.perf_counter() - t0)

        t0 = time.perf_counter()
        big_fn()
        big_times.append(time.perf_counter() - t0)

    time_ratio = min(big_times) / max(min(small_times), 1e-9)
    return time_ratio, call_ratio


def _make_deep_tree(depth: int) -> str:
    # Fixed indent width ensures input size grows strictly O(depth), not O(depth^2).
    parts = [f"n{i} a={i} {{\n" for i in range(depth)]
    parts.append("leaf 1\n")
    parts.extend("}\n" for _ in range(depth))
    return "".join(parts)


def _parse_expect_fail(text: str) -> None:
    try:
        kdl.parse(text)
    except kdl.ParseError:
        return
    msg = "Expected ParseError on malformed scaling input"
    raise AssertionError(msg)


def run_scaling_checks() -> list[CheckResult]:
    results: list[CheckResult] = []
    no_indent_cfg = kdl.PrintConfig(indent="")

    # 1. Repeated properties on a single node: must stay O(N), not O(N^2).
    rp_s = "node " + " ".join(f"p={i}" for i in range(400)) + "\n"
    rp_b = "node " + " ".join(f"p={i}" for i in range(1600)) + "\n"

    # 2. Deeply nested tree parse & print (indent="" keeps output size O(depth)): must stay O(D).
    dt_s = _make_deep_tree(40)
    dt_b = _make_deep_tree(160)
    dn_s = kdl.parse(dt_s)
    dn_b = kdl.parse(dt_b)

    # 3. Many sibling nodes parse & print: must stay O(N).
    sn_s = "".join(f'item-{i % 20} "val-{i}" k={i} flag=#true\n' for i in range(250))
    sn_b = "".join(f'item-{i % 20} "val-{i}" k={i} flag=#true\n' for i in range(1000))
    ds_s = kdl.parse(sn_s)
    ds_b = kdl.parse(sn_b)

    # 4. Long escaped quoted string: must stay O(N).
    es_s = 'node "' + ("abc\\n" * 400) + '"\n'
    es_b = 'node "' + ("abc\\n" * 1600) + '"\n'

    # 5. Multiline string with many lines: must stay O(L).
    ml_s = 'node """\n' + ("    hello world line\n" * 200) + '    """\n'
    ml_b = 'node """\n' + ("    hello world line\n" * 800) + '    """\n'

    # 6. Unclosed string near start of large file: bounded fast path must fail in O(1), not O(N).
    uc_s = 'node "unclosed\n' + ("other arg=1\n" * 1000)
    uc_b = 'node "unclosed\n' + ("other arg=1\n" * 4000)

    cases: list[tuple[str, t.Callable[[], t.Any], t.Callable[[], t.Any], float, float]] = [
        (
            "scaling.repeated_props_4x",
            lambda: kdl.parse(rp_s),
            lambda: kdl.parse(rp_b),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.deep_tree_parse_4x",
            lambda: kdl.parse(dt_s),
            lambda: kdl.parse(dt_b),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.deep_tree_print_4x",
            lambda: dn_s.print(no_indent_cfg),
            lambda: dn_b.print(no_indent_cfg),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.siblings_parse_4x",
            lambda: kdl.parse(sn_s),
            lambda: kdl.parse(sn_b),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.siblings_print_4x",
            ds_s.print,
            ds_b.print,
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.escaped_string_4x",
            lambda: kdl.parse(es_s),
            lambda: kdl.parse(es_b),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.multiline_string_4x",
            lambda: kdl.parse(ml_s),
            lambda: kdl.parse(ml_b),
            MAX_LINEAR_TIME_RATIO_4X,
            MAX_LINEAR_CALL_RATIO_4X,
        ),
        (
            "scaling.unclosed_string_fail_4x",
            lambda: _parse_expect_fail(uc_s),
            lambda: _parse_expect_fail(uc_b),
            MAX_CONST_TIME_RATIO_4X,
            MAX_CONST_CALL_RATIO_4X,
        ),
    ]

    for name, small_fn, big_fn, max_time_ratio, max_call_ratio in cases:
        time_ratio, call_ratio = _measure_scaling(small_fn, big_fn)
        if time_ratio > max_time_ratio:
            # Retry once to rule out transient OS scheduling jitter.
            time_ratio, call_ratio = _measure_scaling(small_fn, big_fn, rounds=7)
        results.append(check_max_float(f"{name}.calls", call_ratio, max_call_ratio, "x"))
        results.append(check_max_float(f"{name}.time", time_ratio, max_time_ratio, "x"))

    return results


# ---------------------------------------------------------------------------
# Suite 4: Self-calibrated CPU-normalized speed ratios
# ---------------------------------------------------------------------------


def _run_calibrated_round(doc_text: str, rounds: int = 7) -> dict[str, float]:
    native_cfg = kdl.ParseConfig()
    raw_cfg = kdl.ParseConfig(nativeUntaggedValues=False, nativeTaggedValues=False)
    doc_nat = kdl.parse(doc_text, native_cfg)
    doc_raw = kdl.parse(doc_text, raw_cfg)

    # Warmup
    run_calibration_kernel()
    kdl.parse(doc_text, native_cfg)
    kdl.parse(doc_text, raw_cfg)
    doc_nat.print()
    doc_raw.print()

    calib_t: list[float] = []
    pn_t: list[float] = []
    pr_t: list[float] = []
    tn_t: list[float] = []
    tr_t: list[float] = []

    # Repeat print 5x per sample so each timed block is ~5ms (same scale as calib & parse),
    # reducing sub-millisecond timer noise.
    print_batch = 5

    for _ in range(rounds):
        t0 = time.perf_counter()
        run_calibration_kernel()
        calib_t.append(time.perf_counter() - t0)

        t0 = time.perf_counter()
        kdl.parse(doc_text, native_cfg)
        pn_t.append(time.perf_counter() - t0)

        t0 = time.perf_counter()
        kdl.parse(doc_text, raw_cfg)
        pr_t.append(time.perf_counter() - t0)

        t0 = time.perf_counter()
        for _ in range(print_batch):
            doc_nat.print()
        tn_t.append((time.perf_counter() - t0) / print_batch)

        t0 = time.perf_counter()
        for _ in range(print_batch):
            doc_raw.print()
        tr_t.append((time.perf_counter() - t0) / print_batch)

    base = max(min(calib_t), 1e-9)
    return {
        "speed.parse_native_vs_calib": min(pn_t) / base,
        "speed.parse_raw_vs_calib": min(pr_t) / base,
        "speed.print_native_vs_calib": min(tn_t) / base,
        "speed.print_raw_vs_calib": min(tr_t) / base,
    }


def run_speed_checks(doc_text: str) -> list[CheckResult]:
    limits: dict[str, float] = {
        "speed.parse_native_vs_calib": MAX_SPEED_RATIO_PARSE_NATIVE,
        "speed.parse_raw_vs_calib": MAX_SPEED_RATIO_PARSE_RAW,
        "speed.print_native_vs_calib": MAX_SPEED_RATIO_PRINT_NATIVE,
        "speed.print_raw_vs_calib": MAX_SPEED_RATIO_PRINT_RAW,
    }
    ratios = _run_calibrated_round(doc_text)
    if any(ratios[k] > limit for k, limit in limits.items()):
        # One automatic retry with extra rounds to avoid false positives under transient CPU contention.
        ratios = _run_calibrated_round(doc_text, rounds=11)

    return [check_max_float(k, ratios[k], limit, "x") for k, limit in limits.items()]


# ---------------------------------------------------------------------------
# CLI entrypoint
# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description="Run hardware-independent performance regression checks for kdl-py.")
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Print every measured metric and its budget (not just failures).",
    )
    args = parser.parse_args()

    t_start = time.perf_counter()
    doc_text = build_bench_doc()

    all_results: list[CheckResult] = []
    all_results.extend(run_call_count_checks(doc_text))
    all_results.extend(run_memory_checks(doc_text))
    all_results.extend(run_scaling_checks())
    all_results.extend(run_speed_checks(doc_text))

    failures = [r for r in all_results if not r.passed]
    elapsed = time.perf_counter() - t_start

    if args.verbose or failures:
        for r in all_results:
            if not args.verbose and r.passed:
                continue
            status = "PASS" if r.passed else "FAIL"
            suffix = f" ({r.detail})" if r.detail and not r.passed else ""
            print(f"  [{status}] {r.name:<38} {r.measured:>10}  (limit {r.limit}){suffix}")

    if failures:
        print(
            f"Performance check FAILED: {len(failures)}/{len(all_results)} checks exceeded budget ({elapsed:.2f}s).",
        )
        return 1

    print(f"Performance check passed ({len(all_results)} checks in {elapsed:.2f}s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
