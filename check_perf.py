#!/usr/bin/env python
"""
Hardware-independent performance regression checker for kdl-py.

Designed to run inside `./lint` across machines with different CPU speeds without
flaky wall-clock cutoffs, using four complementary checks:

1. Deterministic call-count budgets (via cProfile): exact call counts inside `kdl/`,
   total calls, and hot-path invariants (cache hit rate, fast-path usage, lazy loc,
   no ABCMeta overhead). Completely independent of CPU speed.
2. Peak memory budgets (via tracemalloc): catches allocation/retention regressions
   (e.g. eager line-break indexing or quadratic intermediate copies).
3. Asymptotic O(N) scaling guards: compares 4x vs 1x input size on classic quadratic
   traps (repeated props, deep trees, many siblings, long escaped/multiline strings,
   unclosed strings). Ratios are independent of CPU speed.
4. Self-calibrated speed ratios: compares parse/print times against an interleaved
   pure-Python + `re` calibration kernel in the same process, using the minimum of
   multiple interleaved rounds to reject OS jitter while catching pure-CPU inner-loop
   slowdowns regardless of processor speed.

NOTE: This script was generated by Gemini and has not been meaningfully human-reviewed.
"""
from __future__ import annotations

import argparse
import cProfile
import dataclasses
import gc
import os
import pstats
import re
import sys
import time
import tracemalloc
import typing as t

# Force the local kdl package into the import path.
THIS_DIR = os.path.dirname(os.path.realpath(__file__))
if THIS_DIR not in sys.path:
    sys.path.insert(0, THIS_DIR)

import kdl  # noqa: E402  # pylint: disable=wrong-import-position
from kdl import types as kdl_types  # noqa: E402  # pylint: disable=wrong-import-position

KDL_ROOT = os.path.normpath(os.path.dirname(kdl.__file__))

# ---------------------------------------------------------------------------
# Performance budgets (keep these near the top for easy inspection/tuning)
# ---------------------------------------------------------------------------

# Suite 1: Deterministic call-count budgets on the 20-block benchmark doc.
# `kdl` counts only calls inside `kdl/` (immune to Python stdlib changes);
# `total` includes C/stdlib calls and leaves ~15-20% headroom across Python versions.
MAX_PARSE_NATIVE_KDL_CALLS = 3_600  # Expected ~3,060
MAX_PARSE_NATIVE_TOTAL_CALLS = 19_500  # Expected ~16,270
MAX_PARSE_NATIVE_FINALIZE_CALLS = 120  # Expected 100 (tagged values only; ~1,240 if fastUntagged breaks)
MAX_PARSE_NATIVE_SKIP_NODESPACE_CALLS = 80  # Expected 40 (esclines/tags; ~1,500+ without single-space fast path)
MAX_PARSE_NATIVE_LOC_CALLS = 0  # Must stay 0: Stream.loc() is lazy and only runs on ParseError
MAX_ABC_INSTANCECHECK_CALLS = 0  # Must stay 0: Value hierarchy avoids ABCMeta isinstance overhead
MAX_PARSE_RAW_KDL_CALLS = 4_100  # Expected ~3,480
MAX_PARSE_RAW_TOTAL_CALLS = 18_500  # Expected ~15,270
MAX_PRINT_NATIVE_KDL_CALLS = 1_050  # Expected ~820
MAX_PRINT_NATIVE_TOTAL_CALLS = 11_000  # Expected ~8,830
MAX_PRINT_NATIVE_IDENT_CALLS = 300  # Expected 196 cold-cache misses (~2,500+ if _IDENT_CACHE breaks)
MAX_PRINT_RAW_KDL_CALLS = 1_450  # Expected ~1,160
MAX_PRINT_RAW_TOTAL_CALLS = 12_000  # Expected ~9,850
MAX_PRINT_RAW_IDENT_CALLS = 260  # Expected 176 cold-cache misses

# Suite 2: Peak traced heap memory (KB) on the 20-block benchmark doc.
# Generous ~2-2.5x headroom accommodates object-size differences across Python versions / architectures.
MAX_PARSE_NATIVE_PEAK_KB = 500.0  # Expected ~232 KB
MAX_PRINT_NATIVE_PEAK_KB = 350.0  # Expected ~137 KB (steady-state after cache warmup)

# Suite 3: Asymptotic scaling ratios when input size increases 4x.
# For O(N) work, 4x input should take ~4x calls/time while O(N^2) blows up to ~16x.
# For O(1) fail-fast (bounded unclosed-string scan), 4x trailing content should stay ~1x.
MAX_LINEAR_CALL_RATIO_4X = 4.5  # Expected ~3.8x-4.0x
MAX_LINEAR_TIME_RATIO_4X = 8.0  # Expected ~3.9x-4.5x
MAX_CONST_CALL_RATIO_4X = 1.1  # Expected 1.0x
MAX_CONST_TIME_RATIO_4X = 2.5  # Expected ~1.0x (O(N) scan would be ~4x+)

# Suite 4: Self-calibrated speed ratios (`min(kdl_time) / min(calib_time)`).
# Dimensionless multiples of the interleaved calibration kernel; ~55-100% headroom avoids cross-machine noise
# while still catching ~2x+ pure-CPU inner-loop slowdowns.
MAX_SPEED_RATIO_PARSE_NATIVE = 2.40  # Expected ~1.50x-1.55x
MAX_SPEED_RATIO_PARSE_RAW = 2.40  # Expected ~1.50x-1.55x
MAX_SPEED_RATIO_PRINT_NATIVE = 0.55  # Expected ~0.26x-0.28x
MAX_SPEED_RATIO_PRINT_RAW = 0.55  # Expected ~0.29x-0.31x


@dataclasses.dataclass
class CheckResult:
    name: str
    passed: bool
    measured: str
    limit: str
    detail: str = ""


# ---------------------------------------------------------------------------
# Fixed self-contained benchmark corpus (independent of profiler.py)
# ---------------------------------------------------------------------------


def build_bench_doc(blocks: int = 20) -> str:
    chunks: list[str] = []
    for idx in range(blocks):
        bool_lit = "#true" if idx % 2 == 0 else "#false"
        depth = min(idx + 1, 16)
        tree_parts: list[str] = []
        for d in range(depth):
            ind = "    " * (d + 1)
            tree_parts.append(f"{ind}layer-{d} depth={d} weight={1.25 + d * 0.5} active={bool_lit} {{\n")
        leaf_ind = "    " * (depth + 1)
        tree_parts.append(f'{leaf_ind}leaf "item-{idx}" code={200 + idx % 5} (u16){8000 + idx} #null\n')
        for d in range(depth - 1, -1, -1):
            tree_parts.append("    " * (d + 1) + "}\n")
        tree = "".join(tree_parts)
        chunks.append(
            f'service "svc-{idx}" (u16){8000 + idx} enabled={bool_lit} '
            + f"mask=0x{idx + 16:x} mode=0o755 flags=0b1010_0101 ratio=1.{idx:02d}e-2 {{\n"
            + f"    // Comment for service {idx}\n"
            + f'    endpoint "/api/v2/items/{idx}" method="POST" timeout=30_000 retries=3 null_prop=#null\n'
            + f'    pattern ##"^[a-z0-9_-]{{1,32}}$"## #"C:\\data\\shard_{idx}"#\n'
            + '    escaped "line1\\nline2\\t\\"quoted\\"\\u{00e9}\\s end"\n'
            + '    description """\n'
            + f"        Multi-line description for service {idx}.\n"
            + '        Contains "quotes" and indentation.\n'
            + '        """\n'
            + "    limits max-conn=1_024_000 burst=256.5 inf-val=#inf nan-val=#nan \\\n"
            + '        override="first" override="second"\n'
            + '    /- disabled "ignored" foo=123 { nested #false }\n'
            + f'    (meta)audit (date)"2026-11-17" (ipv4)"10.0.0.{idx % 256}" (url)"https://example.com/{idx}" {{\n'
            + f"        tag-{idx % 5} /- #null 10 20 30\n"
            + "    }\n"
            + f"{tree}"
            + "}\n\n",
        )
    return "".join(chunks)


# Pure-Python + `re` calibration kernel exercising the same primitive operations as kdl-py
# (regex matching, string slicing, dict lookups, list appends, join) so its runtime scales
# proportionally with both CPU speed and Python interpreter speed.
_CAL_RE = re.compile(r'[A-Za-z_][A-Za-z0-9_-]*|[0-9]+(?:\.[0-9]+)?|"[^"]*"|[ \t\n]+|.')
_CAL_TEXT = 'node_name key1="value_str" key2=12345 flag=1.5 { child a=1 b=2 }\n' * 250


def run_calibration_kernel() -> int:
    match = _CAL_RE.match
    s = _CAL_TEXT
    n = len(s)
    i = 0
    seen: dict[str, int] = {}
    out: list[str] = []
    append = out.append
    while i < n:
        m = match(s, i)
        assert m is not None
        tok = m.group()
        i = m.end()
        if tok[0] not in " \t\n":
            seen[tok] = seen.get(tok, 0) + 1
            append(tok)
    return len("".join(out))


